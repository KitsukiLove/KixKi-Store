/*
  Sprites pixel-art (iconos de categoría, de interfaz y la oveja) y helpers para dibujarlos (rects, spr).
*/

/* ========= SPRITES PIXEL =========
   Cada dibujo es una cuadrícula de letras: h = color de la categoría, s = sombra, l = luz,
   x = color del texto, y/p/m/w = amarillo/rosa/menta/crema. El punto es vacío. */
export function rects(rows, ox = 0, oy = 0) {
  const m = {};
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === ".") {
        x++;
        continue;
      }
      let x2 = x + 1;
      while (x2 < row.length && row[x2] === ch) x2++;
      (m[ch] = m[ch] || []).push(`M${x + ox} ${y + oy}h${x2 - x}v1h-${x2 - x}z`);
      x = x2;
    }
  });
  return Object.keys(m)
    .map((c) => `<path class="c-${c}" d="${m[c].join("")}"/>`)
    .join("");
}

export const spr = (rows, scale, cls = "") =>
  `<svg class="spr ${cls}" viewBox="0 0 ${rows[0].length} ${rows.length}" width="${rows[0].length * scale}" height="${rows.length * scale}" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${rects(rows)}</svg>`;

